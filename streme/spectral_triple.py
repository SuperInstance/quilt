class QuiltAlgebra:
    """The algebra A of the spectral triple. Generated by the 8 Quilt primitives."""
    
    def __init__(self, dim: int = 8):
        self.dim = dim
        # The 8 primitive generators as operators on a dim-dimensional space
        self.primitives = ['Z_in', 'Z_out', 'JEPA', 'DoubleEntry', 'Vibe', 'GC', 'Murmur', 'Graph']
        # Each primitive is a dim x dim matrix
        self.operators: Dict[str, List[List[float]]] = {}
        self._init_operators()
    
    def _init_operators(self) -> None:
        """Initialize the 8 primitive operators as matrices."""
        n = self.dim
        # Z_in: shift up (creation)
        z_in = [[0.0] * n for _ in range(n)]
        for i in range(n - 1):
            z_in[i][i + 1] = 1.0
        self.operators['Z_in'] = z_in
        # Z_out: shift down (annihilation)
        z_out = [[0.0] * n for _ in range(n)]
        for i in range(n - 1):
            z_out[i + 1][i] = 1.0
        self.operators['Z_out'] = z_out
        # JEPA: projection onto first half
        jepa = [[0.0] * n for _ in range(n)]
        for i in range(n // 2):
            jepa[i][i] = 1.0
        self.operators['JEPA'] = jepa
        # DoubleEntry: swap halves (flip)
        de = [[0.0] * n for _ in range(n)]
        for i in range(n // 2):
            de[i][i + n // 2] = 1.0
            de[i + n // 2][i] = 1.0
        self.operators['DoubleEntry'] = de
        # Vibe: phase rotation
        vibe = [[0.0] * n for _ in range(n)]
        for i in range(n):
            vibe[i][i] = math.cos(2 * math.pi * i / n)
        self.operators['Vibe'] = vibe
        # GC: real diagonal potential
        gc = [[0.0] * n for _ in range(n)]
        for i in range(n):
            gc[i][i] = i / n
        self.operators['GC'] = gc
        # Murmur: discrete derivative
        murmur = [[0.0] * n for _ in range(n)]
        for i in range(n - 1):
            murmur[i][i + 1] = 1.0
            murmur[i + 1][i] = -1.0
        self.operators['Murmur'] = murmur
        # Graph: anti-diagonal flip
        graph = [[0.0] * n for _ in range(n)]
        for i in range(n):
            graph[i][n - 1 - i] = 1.0
        self.operators['Graph'] = graph
    
    def commutator(self, a_name: str, b_name: str) -> List[List[float]]:
        """Compute [A, B] = AB - BA."""
        n = self.dim
        A = self.operators[a_name]
        B = self.operators[b_name]
        result = [[0.0] * n for _ in range(n)]
        for i in range(n):
            for j in range(n):
                for k in range(n):
                    result[i][j] += A[i][k] * B[k][j] - B[i][k] * A[k][j]
        return result
    
    def trace(self, op_name: str) -> float:
        """Trace of an operator."""
        return sum(self.operators[op_name][i][i] for i in range(self.dim))
    
    def is_self_adjoint(self, op_name: str) -> bool:
        """Check if operator is self-adjoint (Hermitian)."""
        op = self.operators[op_name]
        for i in range(self.dim):
            for j in range(self.dim):
                if abs(op[i][j] - op[j][i]) > 1e-9:
                    return False
        return True


class QuiltHilbertSpace:
    """The Hilbert space H of the spectral triple. Spanned by {γ, η}."""
    
    def __init__(self, n_cells: int = 4):
        self.n_cells = n_cells
        # H = C^2 (spanned by γ, η) tensored with C^{n_cells} (positions)
        self.dim = 2 * n_cells
        # State: list of (γ, η) pairs at each cell
        self.states: List[Tuple[float, float]] = []
        # Initialize with γ=η=0.5 (conservation holds: γ+η=1)
        for i in range(n_cells):
            self.states.append((0.5, 0.5))
    
    def conservation_holds(self) -> bool:
        """Check γ+η=1 for all cell states."""
        return all(abs(g + h - 1.0) < 1e-9 for g, h in self.states)
    
    def inner_product(self, state_a: List[float], state_b: List[float]) -> float:
        """Inner product <a|b>."""
        return sum(a * b for a, b in zip(state_a, state_b))
    
    def norm(self, state: List[float]) -> float:
        """||state||."""
        return math.sqrt(self.inner_product(state, state))


class QuiltDiracOperator:
    """The Dirac operator D of the spectral triple. Encodes γ+η=1."""
    
    def __init__(self, dim: int):
        self.dim = dim
        # D encodes the conservation γ+η=1
        # D² = Δ (Laplacian)
        # Off-diagonal: connections between γ and η
        self.matrix: List[List[float]] = [[0.0] * dim for _ in range(dim)]
        self._build()
    
    def _build(self) -> None:
        """Build the Dirac operator."""
        n = self.dim
        for i in range(n):
            # Diagonal: ensures γ+η=1 holds
            self.matrix[i][i] = 1.0
            # Off-diagonal: spectral flow
            if i + 1 < n:
                self.matrix[i][i + 1] = 0.5
                self.matrix[i + 1][i] = 0.5
    
    def is_self_adjoint(self) -> bool:
        """D must be self-adjoint."""
        for i in range(self.dim):
            for j in range(self.dim):
                if abs(self.matrix[i][j] - self.matrix[j][i]) > 1e-9:
                    return False
        return True
    
    def trace(self) -> float:
        """Tr(D)."""
        return sum(self.matrix[i][i] for i in range(self.dim))
    
    def determinant(self) -> float:
        """det(D) — simplified as product of diagonals."""
        result = 1.0
        for i in range(self.dim):
            result *= self.matrix[i][i]
        return result


